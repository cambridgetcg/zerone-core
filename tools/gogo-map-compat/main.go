// Command gogo-map-compat generates concrete map-entry messages for the pinned
// Cosmos SDK's descriptor-based unknown-field validator. protoc-gen-go correctly
// represents maps natively, but SDK unknownproto requires a concrete gogo message
// even for synthetic entries. This bridge retains the ORIGINAL descriptors and
// does not replace the decoder, relax validation, or re-encode signed bytes.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"strings"

	knowledge "github.com/zerone-chain/zerone/x/knowledge/types"
	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/reflect/protodesc"
	"google.golang.org/protobuf/reflect/protoreflect"
	"google.golang.org/protobuf/types/descriptorpb"
	"google.golang.org/protobuf/types/pluginpb"
)

func main() {
	check := flag.Bool("check", false, "check generated bytes without writing")
	out := flag.String("out", "x/knowledge/types/gogo_map_entries.pb.go", "generated output")
	flag.Parse()
	generated, err := generate([]protoreflect.FileDescriptor{
		knowledge.File_zerone_knowledge_v1_genesis_proto,
		knowledge.File_zerone_knowledge_v1_types_proto,
	})
	if err != nil {
		panic(err)
	}
	if *check {
		actual, err := os.ReadFile(*out)
		if err != nil {
			panic(err)
		}
		if !bytes.Equal(actual, generated) {
			panic("gogo map compatibility output is stale; run make proto-gen")
		}
		return
	}
	if err := os.WriteFile(*out, generated, 0644); err != nil {
		panic(err)
	}
}

func generate(roots []protoreflect.FileDescriptor) ([]byte, error) {
	// protogen supplies the same Go identifiers as protoc-gen-go, including
	// nested-message names. Dependency order is deterministic, not a map walk.
	req := &pluginpb.CodeGeneratorRequest{}
	seen := map[string]bool{}
	var visit func(protoreflect.FileDescriptor)
	visit = func(f protoreflect.FileDescriptor) {
		if seen[f.Path()] {
			return
		}
		seen[f.Path()] = true
		for i := 0; i < f.Imports().Len(); i++ {
			visit(f.Imports().Get(i))
		}
		req.ProtoFile = append(req.ProtoFile, protodesc.ToFileDescriptorProto(f))
	}
	for _, f := range roots {
		visit(f)
		req.FileToGenerate = append(req.FileToGenerate, f.Path())
	}
	plugin, err := (protogen.Options{}).New(req)
	if err != nil {
		return nil, err
	}
	var b bytes.Buffer
	fmt.Fprintln(&b, "// Code generated by tools/gogo-map-compat from canonical protobuf descriptors. DO NOT EDIT.")
	fmt.Fprintln(&b, "// Concrete synthetic entries preserve SDK unknownproto validation; native maps remain the application API.")
	fmt.Fprintln(&b, "package types\n\nimport gogoproto \"github.com/cosmos/gogoproto/proto\"")
	var names []string
	valueTypes := map[protoreflect.FullName]bool{}
	var registerValue func(*protogen.Message) error
	registerValue = func(m *protogen.Message) error {
		if m.Desc.IsMapEntry() || valueTypes[m.Desc.FullName()] {
			return nil
		}
		if m.GoIdent.GoImportPath != "github.com/zerone-chain/zerone/x/knowledge/types" {
			return fmt.Errorf("external map value dependency %s requires reviewed support", m.Desc.FullName())
		}
		valueTypes[m.Desc.FullName()] = true
		names = append(names, fmt.Sprintf("if gogoproto.MessageType(%q) == nil { gogoproto.RegisterType((*%s)(nil), %q) }", m.Desc.FullName(), m.GoIdent.GoName, m.Desc.FullName()))
		for _, f := range m.Fields {
			if f.Message != nil {
				if err := registerValue(f.Message); err != nil {
					return err
				}
			}
		}
		return nil
	}
	var walk func(*protogen.Message) error
	walk = func(m *protogen.Message) error {
		if m.Desc.IsMapEntry() {
			name := "gogoCompat" + m.GoIdent.GoName
			names = append(names, fmt.Sprintf("gogoproto.RegisterType((*%s)(nil), %q)", name, m.Desc.FullName()))
			fmt.Fprintf(&b, "\ntype %s struct {\n", name)
			for _, f := range m.Fields {
				if f.Message != nil {
					if err := registerValue(f.Message); err != nil {
						return err
					}
				}
				goType, wire, err := fieldType(f)
				if err != nil {
					return err
				}
				fmt.Fprintf(&b, "%s %s `protobuf:%q json:%q`\n", f.GoName, goType,
					fmt.Sprintf("%s,%d,opt,name=%s,proto3", wire, f.Desc.Number(), f.Desc.Name()), string(f.Desc.Name())+",omitempty")
			}
			fmt.Fprintln(&b, "}")
			fmt.Fprintf(&b, "func (m *%s) Reset() { *m = %s{} }\n", name, name)
			fmt.Fprintf(&b, "func (m *%s) String() string { return gogoproto.CompactTextString(m) }\n", name)
			fmt.Fprintf(&b, "func (*%s) ProtoMessage() {}\n", name)
			// Descriptor() returns the original top-level file's gzip bytes and
			// exact nested index. No copied or invented field descriptor exists.
			path := m.Location.Path
			if len(path) < 4 || path[0] != 4 {
				return fmt.Errorf("unexpected map descriptor path: %v", path)
			}
			top := plugin.FilesByPath[m.Location.SourceFile].Messages[path[1]]
			var indexes []string
			for i := 1; i < len(path); i += 2 {
				indexes = append(indexes, fmt.Sprint(path[i]))
			}
			fmt.Fprintf(&b, "func (*%s) Descriptor() ([]byte, []int) { b, _ := (*%s)(nil).Descriptor(); return b, []int{%s} }\n", name, top.GoIdent.GoName, strings.Join(indexes, ","))
		}
		for _, child := range m.Messages {
			if err := walk(child); err != nil {
				return err
			}
		}
		return nil
	}
	for _, file := range plugin.Files {
		if !file.Generate {
			continue
		}
		for _, m := range file.Messages {
			if err := walk(m); err != nil {
				return nil, err
			}
		}
	}
	fmt.Fprintln(&b, "\nfunc init() {")
	for _, name := range names {
		fmt.Fprintln(&b, name)
	}
	fmt.Fprintln(&b, "}")
	return format.Source(b.Bytes())
}

func fieldType(f *protogen.Field) (string, string, error) {
	// Fail generation for an unsupported future shape rather than producing an
	// adapter with guessed semantics. Current canonical maps use these kinds.
	switch f.Desc.Kind() {
	case protoreflect.StringKind:
		return "string", "bytes", nil
	case protoreflect.Uint64Kind:
		return "uint64", "varint", nil
	case protoreflect.MessageKind:
		if f.Message.GoIdent.GoImportPath != "github.com/zerone-chain/zerone/x/knowledge/types" {
			return "", "", fmt.Errorf("external map message %s requires reviewed generator support", f.Desc.FullName())
		}
		return "*" + f.Message.GoIdent.GoName, "bytes", nil
	default:
		return "", "", fmt.Errorf("unsupported map field %s (%s)", f.Desc.FullName(), descriptorpb.FieldDescriptorProto_Type(f.Desc.Kind()))
	}
}
